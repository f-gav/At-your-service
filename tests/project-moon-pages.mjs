import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DEFAULT_MOON_ORDER,parseMoonOrder,moveMoonPage,shiftMoonPage} from '../src/features/project-moon/page-order.ts';
import {emptyMoonSheet,readMoonSheet,saveMoonSheet} from '../src/features/project-moon/model.ts';

const content = path => readFileSync(new URL(path,import.meta.url),'utf8');
assert.deepEqual(DEFAULT_MOON_ORDER,['dossier','combat','equipment','about','notes']);
assert.deepEqual(parseMoonOrder(null),DEFAULT_MOON_ORDER);
assert.deepEqual(parseMoonOrder(['notes','combat','dossier','about']),
  ['notes','combat','equipment','dossier','about'],
  'Old custom page orders must retain their relative positions');
assert.deepEqual(parseMoonOrder(['notes','combat','combat','bad']),['notes','combat','equipment','dossier','about']);
assert.deepEqual(moveMoonPage(DEFAULT_MOON_ORDER,'notes','dossier'),['notes','dossier','combat','equipment','about']);
assert.deepEqual(shiftMoonPage(DEFAULT_MOON_ORDER,'combat',-1),['combat','dossier','equipment','about','notes']);
assert.deepEqual(shiftMoonPage(DEFAULT_MOON_ORDER,'dossier',-1),DEFAULT_MOON_ORDER);
assert.deepEqual(shiftMoonPage(DEFAULT_MOON_ORDER,'notes',1),DEFAULT_MOON_ORDER);
const before=emptyMoonSheet();before.notes[0].body='<p>Запись кампании</p>';before.skills[0].title='Удар';
const after={...before,pageOrder:moveMoonPage(before.pageOrder,'notes','dossier')};
const loaded=readMoonSheet(saveMoonSheet({oldKey:'still here'},after));
assert.deepEqual(loaded.pageOrder,['notes','dossier','combat','equipment','about']);
assert.equal(loaded.notes[0].body,'<p>Запись кампании</p>');
assert.equal(loaded.skills[0].title,'Удар');
assert.deepEqual(readMoonSheet({projectMoonSheet:{fields:{rank:'2'}}}).pageOrder,DEFAULT_MOON_ORDER);

const sheet=content('../src/features/project-moon/ProjectMoonSheet.tsx');
const pages=content('../src/features/project-moon/MoonPageSettingsDialog.tsx');
const css=content('../src/features/project-moon/ProjectMoonSheet.css');
const globalCSS=content('../src/styles.css');
assert.ok(sheet.includes('pageOrder.map(page => <article'));
assert.ok(sheet.includes("id={'moon-sheet-page-' + page}"));
assert.ok(sheet.includes('aria-label="Страницы листа Project Moon"'));
assert.ok(sheet.includes('Помощь в навигации'));
assert.ok(sheet.includes('Страницы листа…'));
assert.ok(sheet.includes('<MoonPageSettingsDialog'));
assert.ok(sheet.includes('window.localStorage'));
assert.ok(sheet.includes('pf-navigation-help-active'));
assert.ok(sheet.includes('scrollIntoView'));
assert.ok(sheet.includes("!previewMode && navigationHelp"));
assert.ok(!sheet.includes('className="moon-tabs"'));
assert.ok(pages.includes('moveMoonPage'));
assert.ok(pages.includes('shiftMoonPage'));
assert.ok(pages.includes('draggable={!disabled}'));
assert.ok(css.includes('.moon-sheet-scroll .moon-paper'));
assert.ok(css.includes('break-after: page'));
assert.ok(globalCSS.includes('.character-prmoon .character-system { color: #29445f; }'));
assert.ok(!globalCSS.includes("font-family: Georgia, 'Times New Roman', serif;\\n  font-size: 20px;"));
for(const russian of ['Режущий','Колющий','Дробящий']) assert.ok(sheet.includes(russian));
for(const english of ["value:'Slash'","value:'Pierce'","value:'Blunt'"]) assert.ok(sheet.includes(english));
assert.ok(!sheet.includes('<th>SLASH</th>'));
console.log('PASS: Pr. Moon matches PF2e badge, stacked A4 navigation and translated damage without data loss');
