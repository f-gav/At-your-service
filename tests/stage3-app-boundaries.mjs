import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {nextCharacterOrder,newCharacterDetails,copyCharacterDetails,characterCopyName} from '../src/features/character/character-operations.ts';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const app=read('src/App.tsx');
const editor=read('src/features/character/CharacterEditor.tsx');
const branding=read('src/components/SiteBranding.tsx');
assert.ok(app.includes("import CharacterEditor from './features/character/CharacterEditor'"));
assert.ok(!app.includes('function CharacterEditor('),'Draft editor must not live in App');
assert.ok(editor.includes('useAutoSave')&&editor.includes('recoverLocalDraft'));
assert.ok(branding.includes('function SiteLogo')&&branding.includes('function HeroEmblem'));
assert.ok(app.includes('nextCharacterOrder(characters)')&&app.includes('copyCharacterDetails(character.details)'));
assert.equal(nextCharacterOrder([{sort_order:3},{sort_order:8}]),9);
assert.equal(newCharacterDetails('pf2e','alternative').pathfinderSheet.pf2e_layout,'alternative');
assert.equal(newCharacterDetails('prmoon').projectMoonSheet.inventoryColumns,1);
assert.equal(characterCopyName('Герой'),'Герой (копия)');
const original={pathfinderSheet:{name:'Old',items:[{name:'old'}]}};
const copied=copyCharacterDetails(original);
assert.notEqual(copied.pathfinderSheet,original.pathfinderSheet);
assert.deepEqual(copied.pathfinderSheet,original.pathfinderSheet);
console.log('PASS: App boundaries, draft editor, branding and character operation contracts');
