import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {insertionMenuPosition} from '../src/features/pathfinder/insert-menu-position.ts';
import {initialNavigationRect,clampNavigationRect,moveNavigationRect,resizeNavigationRect,parseNavigationRect} from '../src/features/pathfinder/floating-navigation-geometry.ts';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const viewport={width:1366,height:800};
const caret={left:310,top:145,bottom:164,height:19};
const tall={left:80,top:95,bottom:610,height:515};
assert.deepEqual(insertionMenuPosition(caret,tall,viewport),{left:310,top:170},
  'Menu must sit under the caret, not under a large editor field');
const emptyCaret={left:0,top:0,bottom:0,height:0};
const byMouse=insertionMenuPosition(emptyCaret,tall,viewport,{x:200,y:180});
assert.deepEqual(byMouse,{left:200,top:186},
  'Zero-size range must use actual click coordinates');
assert.equal(insertionMenuPosition(emptyCaret,tall,viewport).top,125,
  'Without mouse, fallback remains on the first text line');
const nearBottom=insertionMenuPosition({left:380,top:780,bottom:800,height:20},tall,viewport);
assert.ok(nearBottom.top<780,'Toolbar moves above caret at viewport bottom');
assert.equal(insertionMenuPosition(caret,tall,{width:375,height:800}).left,8,
  'Mobile toolbar is clamped within the screen');
const sheet=read('../src/features/pathfinder/PathfinderSheet.tsx');
const css=read('../src/features/pathfinder/PathfinderSheet.css');
const floating=read('../src/features/pathfinder/FloatingPageNavigation.tsx');
const floatingCss=read('../src/features/pathfinder/FloatingPageNavigation.css');
const rich=read('../src/features/pathfinder/RichField.tsx');
const admin=read('../src/features/pathfinder/TemplateAdmin.tsx');
const schema=read('../src/features/pathfinder/editor-schema.ts');
const layout=read('../src/features/pathfinder/layout.ts');
assert.match(rich,/insertionMenuPosition\(rect,fallback/);
assert.match(rich,/pointerRef\.current=\{x:event\.clientX,y:event\.clientY\}/);
assert.match(sheet,/Помощь в навигации/);
assert.match(sheet,/navigationHelp&&<FloatingPageNavigation system="pf2e"/);
assert.match(floating,/onPointerDown=\{event=>start\(event,'move'\)\}/);
assert.match(floating,/onPointerDown=\{event=>start\(event,'resize'\)\}/);
assert.match(floating,/ays-floating-pages-v1-/);
assert.match(floating,/window\.localStorage\.setItem\(storageKey/);
assert.match(floating,/onKeyDown=\{event=>arrows\(event,'move'\)\}/);
assert.match(sheet,/pf-sheet-page-\$\{page\}/);
assert.match(sheet,/scrollIntoView\(\{/);
assert.match(sheet,/ays-pf2e-navigation-help/);
assert.match(floating,/aria-current=\{activePage===page.id\?'page':undefined\}/);
assert.match(sheet,/visiblePages\.map\(page=>/);
assert.match(floatingCss,/@container \(max-width: 114px\)/);
assert.match(floatingCss,/\.pf-navigation-help-label \{display:none;\}/);
assert.match(admin,/Поворот четверти круга/);
assert.match(admin,/<option value="quarter">Четверть круга<\/option>/);
assert.match(schema,/tradition_arcane:0, tradition_occult:90/);
assert.match(schema,/tradition_primal:270, tradition_divine:180/);
assert.match(schema,/TOGGLE_ROTATIONS.includes\(a.toggleRotation\)/);
assert.match(layout,/toggleRotation\?: 0 \| 90 \| 180 \| 270/);
console.log('Caret-anchored insert menu, quarter-turn magic toggles and optional four-page navigator regression checks passed.');

const desktop=initialNavigationRect({width:1440,height:900},5);
assert.ok(desktop.width>=220&&desktop.x>1100,'Desktop starts as a readable panel near the right edge');
const phone=initialNavigationRect({width:375,height:667},5);
assert.ok(phone.width<=50,'Phone starts with a compact navigator');
const dragged=moveNavigationRect(desktop,-900,-2000,{width:1440,height:900});
assert.equal(dragged.y,8,'Drag never moves outside the top viewport edge');
assert.ok(dragged.x>=8);
const expanded=resizeNavigationRect(phone,-190,150,{width:375,height:667});
assert.ok(expanded.width>150&&expanded.width<=359,'Compact mobile navigator can be expanded by its handle');
assert.ok(expanded.height>phone.height);
const constrained=clampNavigationRect({x:1400,y:860,width:900,height:500},{width:375,height:667});
assert.ok(constrained.x+constrained.width<=367);
assert.ok(constrained.y+constrained.height<=659);
assert.deepEqual(parseNavigationRect(JSON.stringify(expanded),{width:375,height:667}),expanded);
assert.equal(parseNavigationRect('{broken',{width:375,height:667}),null);
assert.equal(parseNavigationRect('{"x":"bad"}',{width:375,height:667}),null);
console.log('PASS: drag, keyboard controls, resizable compact menu, viewport clamping and local persistence.');
