import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(new URL(path,import.meta.url),'utf8');
const wordmark=read('../public/wordmark.svg');
const css=read('../src/styles.css');
const app=read('../src/App.tsx');
const subset=readFileSync(new URL('../src/assets/tilda-script-labels.woff2',import.meta.url));
assert.ok(wordmark.includes('<path d='),'The main site wordmark is vector outlines');
assert.ok(!/<text(?:\\s|>)/i.test(wordmark),'The main site wordmark is NOT text in a font');
assert.ok(app.includes('wordmark.svg'));
assert.equal(subset.toString('ascii',0,4),'wOF2');
assert.ok(subset.byteLength<15000,'Bundled script is a small subset, not a complete design source');
assert.match(css,/font-family: 'Tilda Script'/);
const prmoonFont=readFileSync(new URL('../src/assets/tilda-script-prmoon-semibold.woff2',import.meta.url));
assert.equal(prmoonFont.toString('ascii',0,4),'wOF2','Pr. Moon webfont must have WOFF2 signature');
assert.ok(prmoonFont.byteLength>1500 && prmoonFont.byteLength<15000,'Subset should be small, not the complete OTF');
assert.match(css,/@font-face\s*\{[\s\S]*?font-family: 'Tilda Script Moon'/);
assert.match(css,/url\('\.\/assets\/tilda-script-prmoon-semibold\.woff2'\)/);
assert.match(css,/\.character-prmoon \.character-system\s*\{[\s\S]*?font-family: 'Tilda Script Moon'/);
assert.doesNotMatch(css,/Lobster/,'The badge should not depend on an externally fetched fallback font');
console.log('PASS: Pr. Moon uses original Tilda Script SemiBold; other systems preserve Tilda Script');
