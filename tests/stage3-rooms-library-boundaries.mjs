import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {filterLibrarySpells,sourceFilteredSpells,paginateLibrarySpells,hasLibraryFilters,RESULTS_PER_PAGE} from '../src/features/spell-library/library-query.ts';
import {DEFAULT_SPELL_FILTERS} from '../src/features/spell-library/catalog.ts';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const rooms=read('src/features/rooms/RoomsHub.tsx');
const repo=read('src/features/rooms/room-repository.ts');
const lib=read('src/features/spell-library/SpellLibrary.tsx');
assert.ok(!rooms.includes(".from('game_rooms')")&&!rooms.includes(".from('game_room_members')")&&!rooms.includes(".from('game_room_rolls')"));
assert.ok(!rooms.includes(".rpc('join_game_room'"));
for(const guard of [".eq('user_id',userId)",".eq('room_id',roomId)",".eq('character_id',characterId)",".rpc('join_game_room'", "p_code:code.trim().toUpperCase()",".limit(80)"])assert.ok(repo.includes(guard),'Room security/data contract lost '+guard);
assert.ok(rooms.includes('takeRoomRequestPermit('),'Client join throttling must remain');
assert.ok(rooms.includes("postgres_changes"),'Live room subscriptions remain enabled');
assert.ok(lib.includes('filterLibrarySpells(')&&lib.includes('paginateLibrarySpells('));
assert.equal(RESULTS_PER_PAGE,50);
assert.equal(filterLibrarySpells([],DEFAULT_SPELL_FILTERS,'mine','pf2e').length,0);
const sample=[{id:'a',source:{name:'A'}},{id:'b',source:{name:'B'}},{id:'c',source:{name:'A'}}];
assert.deepEqual(sourceFilteredSpells(sample,'A').map(x=>x.id),['a','c']);
assert.deepEqual(paginateLibrarySpells(sample,2).map(x=>x.id),['a','b']);
assert.equal(hasLibraryFilters(DEFAULT_SPELL_FILTERS,'all','all'),false);
assert.equal(hasLibraryFilters(DEFAULT_SPELL_FILTERS,'A','all'),true);
console.log('PASS: rooms queries & security, library filter/source/paging boundaries');
